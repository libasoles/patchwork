// Letter-grid patterns transcribed from Dominique Douat's 1722 book
// "Méthode pour faire une infinité de desseins différens avec des carreaux
//  mi-partis de deux couleurs par une ligne diagonale".
//
// Each tile is a square split by a diagonal into a colored half and a white
// half. The letter records where the colored right-angle corner sits:
//   A = bottom-left   B = top-left   C = top-right   D = bottom-right
// A pattern is a grid of these letters (read left→right, top→bottom).
//
// Source rows are stored compactly as strings and expanded to a letter matrix
// at module load. Transcribed from the scanned plates; a handful of cells in
// the dense 24×24 designs are best-effort reads.

export type DouatLetter = "A" | "B" | "C" | "D";

export interface DouatPattern {
  /** 1-based number as printed in the book. */
  id: number;
  /** Human label, e.g. "Dessein 1". */
  name: string;
  /** Which part of the book the grid comes from. */
  set: "plate" | "table256";
  rows: number;
  cols: number;
  /** rows × cols matrix of single-letter orientations. */
  grid: DouatLetter[][];
}

interface RawPattern {
  id: number;
  name: string;
  set: "plate" | "table256";
  /** Each string is one grid row of letters. */
  rows: string[];
}

function expand(raw: RawPattern): DouatPattern {
  const grid = raw.rows.map((s) => s.split("") as DouatLetter[]);
  return {
    id: raw.id,
    name: raw.name,
    set: raw.set,
    rows: grid.length,
    cols: grid[0]?.length ?? 0,
    grid,
  };
}

